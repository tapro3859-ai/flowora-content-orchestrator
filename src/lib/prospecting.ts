const PREFIXES = ["Cedar", "Harbor", "Saffron", "Atlas", "Oasis", "Medina", "Coral", "Amber", "Olive", "Zenith", "Dune", "Indigo"];

export const MAX_RESULT_OPTIONS = [10, 25, 50] as const;

export interface ProspectQuery {
  categoryId: string;
  location: string;
  lang: ProspectLang;
  fields: ProspectField[];
  maxResults: number;
}

export interface Prospect {
  id: string;
  name: string;
  category: string;
  city: string;
  phone: string;
  website: string;
  rating: string;
  source: string;
  fictional: true;
}

export interface ProspectProvider {
  id: string;
  isLive: boolean;
  search(query: ProspectQuery): Promise<Prospect[]>;
}

function seeded(seedText: string) {
  let h = 2166136261;
  for (let i = 0; i < seedText.length; i++) {
    h ^= seedText.charCodeAt(i);
    h = Math.imul(h, 16777619);
  }
  return () => {
    h = Math.imul(h ^ (h >>> 15), 2246822507);
    h = Math.imul(h ^ (h >>> 13), 3266489909);
    h ^= h >>> 16;
    return (h >>> 0) / 4294967296;
  };
}

const slug = (s: string) =>
  s.toLowerCase().normalize("NFD").replace(/[\u0300-\u036f]/g, "").replace(/[^a-z0-9]+/g, "-").replace(/(^-|-$)/g, "");

export function generateSampleProspects(query: ProspectQuery): Prospect[] {
  const cat = CATEGORIES.find((c) => c.id === query.categoryId) ?? CATEGORIES[0];
  const city = query.location.trim() || "Casablanca";
  const rand = seeded(`${cat.id}|${city.toLowerCase()}`);
  const count = Math.max(1, Math.min(50, Math.floor(query.maxResults)));
  return Array.from({ length: count }, (_, i) => {
    const prefix = PREFIXES[Math.floor(rand() * PREFIXES.length)];
    const noun = cat.nouns[Math.floor(rand() * cat.nouns.length)];
    const n = String(i + 1).padStart(2, "0");
    const name = `${prefix} ${noun} ${n} (Sample)`;
    const hasRating = rand() > 0.2;
    return {
      id: `${cat.id}-${n}`,
      name,
      category: cat.label[query.lang],
      city,
      // Deliberately non-dialable placeholder numbers.
      phone: `+212 000-000-${String(100 + i).slice(-3)}`,
      website: `${slug(`${prefix}-${noun}`)}-${n}.example`,
      rating: hasRating ? (3.6 + rand() * 1.3).toFixed(1) : "—",
      source: "Sample Data",
      fictional: true,
    };
  });
}

export const sampleProvider: ProspectProvider = {
  id: "sample",
  isLive: false,
  search: async (q) => generateSampleProspects(q),
};

function csvCell(value: string) {
  return /[",\n\r]/.test(value) ? `"${value.replace(/"/g, '""')}"` : value;
}

export function toCsv(rows: Prospect[], fields: ProspectField[], lang: ProspectLang): string {
  const header = fields.map((f) => csvCell(FIELD_LABELS[lang][f])).join(",");
  const body = rows.map((r) => fields.map((f) => csvCell(r[f])).join(","));
  return ["# Sample Data - fictional records generated by the FLOWORA demo", header, ...body].join("\n");
}
